def base_style(doc):
    st = doc.styles['Normal']
    st.font.name = 'Times New Roman'
    st.font.size = Pt(12)
    pf = st.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.DOUBLE
    pf.space_after = Pt(0)


def p_norm(doc, text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True):
    par = doc.add_paragraph()
    par.alignment = align
    if indent:
        par.paragraph_format.first_line_indent = Cm(1.25)
    add_rich(par, text)
    return par


def p_center(doc, text, bold=False, italic=False):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = par.add_run(text)
    r.bold = bold
    r.italic = italic
    return par


def heading(doc, text):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.space_before = Pt(12)
    r = par.add_run(text.upper())
    r.bold = True
    return par


def equation(doc, png, number=None):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    with PILImage.open(png) as im:
        w_px, _ = im.size
    width = Cm(min(14.0, w_px / 4 / 96 * 2.54))   # scale=4, ~96 dpi базовых
    par.add_run().add_picture(png, width=width)
    if number is not None:
        par.add_run(f'    ({number})')
    return par


def table(doc, caption, header, rows, widths=None):
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.LEFT
    add_rich(cap, caption)
    for r in cap.runs:
        r.bold = False
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(header):
        cell = t.rows[0].cells[j]
        par = cell.paragraphs[0]
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
        add_rich(par, h)
        for r in par.runs:
            r.bold = True
    for i, row in enumerate(rows, start=1):
        for j, v in enumerate(row):
            cell = t.rows[i].cells[j]
            par = cell.paragraphs[0]
            par.alignment = WD_ALIGN_PARAGRAPH.CENTER if j else WD_ALIGN_PARAGRAPH.LEFT
            add_rich(par, v)
            if row[0].startswith('Среднее') or v.startswith('**'):
                pass
    doc.add_paragraph()
    return t

