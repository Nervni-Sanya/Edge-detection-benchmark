EQUATIONS = {
    'tensor':   r'M=\sum_{k}(\nabla C_{k})(\nabla C_{k})^{\mathsf T}='
                r'\begin{pmatrix} E & F \\ F & G \end{pmatrix}',
    'tensor2':  r'E=\sum_{k}(C_{k,x})^{2},\qquad F=\sum_{k}C_{k,x}C_{k,y},'
                r'\qquad G=\sum_{k}(C_{k,y})^{2}',
    'response': r'E_{L}=\sqrt{(\nabla X\cdot L)^{2}+(\nabla Y\cdot L)^{2}}\cdot'
                r'\left(1+\alpha\,\frac{C_{Z}-T}{255}\right)',
    'identity': r'(u\cdot L)^{2}=L^{\mathsf T}\,(u\,u^{\mathsf T})\,L',
    'quadform': r'(\nabla X\cdot L)^{2}+(\nabla Y\cdot L)^{2}='
                r'L^{\mathsf T}M_{XY}\,L',
    'radial':   r'E_{\varphi}=\sqrt{\lambda_{\max}\cos^{2}\varphi+'
                r'\lambda_{\min}\sin^{2}\varphi}',
    'elliptic': r'\bar{E}=\frac{2}{\pi}\,\sqrt{\lambda_{\max}}\;'
                r'\mathrm{E}\!\left(\sqrt{1-\lambda_{\min}/\lambda_{\max}}\right)',
    'full':     r'E_{L}^{\mathrm{full}}=h(C_{Z})\,\sqrt{L^{\mathsf T}M_{XY}\,L},'
                r'\qquad h(C_{Z})=1+\alpha\,\frac{C_{Z}-T}{255}',
}


def render_equations():
    os.makedirs(EQ_DIR, exist_ok=True)
    paths = {}
    for name, tex in EQUATIONS.items():
        png = os.path.join(EQ_DIR, f'{name}.png')
        if not os.path.exists(png):
            mml = l2m.convert(tex)
            svg = ziamath.Math(mml, size=13).svg()
            svg_path = os.path.join(EQ_DIR, f'{name}.svg')
            with open(svg_path, 'w') as f:
                f.write(svg)
            cairosvg.svg2png(url=svg_path, write_to=png, scale=4)
        paths[name] = png
    return paths

