TOKEN = re.compile(r'([_^])\{([^{}]*)\}')


def add_rich(par, text, italic=False):
    """Добавляет в абзац текст с поддержкой _{...} и ^{...}."""
    pos = 0
    for m in TOKEN.finditer(text):
        if m.start() > pos:
            r = par.add_run(text[pos:m.start()])
            r.italic = italic
        r = par.add_run(m.group(2))
        r.italic = italic
        if m.group(1) == '_':
            r.font.subscript = True
        else:
            r.font.superscript = True
        pos = m.end()
    if pos < len(text):
        r = par.add_run(text[pos:])
        r.italic = italic

